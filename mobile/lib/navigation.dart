import 'package:flutter/material.dart';

/// Глобальный ключ навигатора — нужен, чтобы ApiClient мог сам перекинуть на экран логина
/// при истечении/невалидности токена (401), не размазывая эту логику по каждому экрану.
final navigatorKey = GlobalKey<NavigatorState>();

/// Первый экран после входа — для каждой роли. Дашборд для большинства ролей показывает
/// статистику и уведомления по ЗАКАЗАМ (карточки "Новых заказов"/"Готовы к отгрузке" ведут в
/// общий список заказов) — это не относится к зоне ответственности склада ГП, поэтому
/// WAREHOUSE_FG сразу попадает на свой профильный экран, а не на Дашборд. WAREHOUSE_RAW
/// (склад сырья) теперь тоже видит Дашборд ('/') — но DashboardScreen сам показывает для
/// этой роли отдельный производственный дашборд (заявки на сырьё), а не про заказы,
/// см. DashboardScreen._isWarehouseRaw.
String homeRouteForRole(String? role) {
  switch (role) {
    case 'WAREHOUSE_FG':
      return '/orders';
    default:
      return '/';
  }
}
